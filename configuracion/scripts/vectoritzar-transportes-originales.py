#!/usr/bin/env python3
"""Trace original five 320x210 illustrated WebPs into genuine path-based SVGs.

Do NOT embed images in SVG. Compare rendered SVG against the real original image,
and refuse to publish if any illustration differs too much.
"""
from __future__ import annotations
from pathlib import Path
from io import BytesIO
import re
import sys
import tempfile
import xml.etree.ElementTree as ET
from PIL import Image, ImageChops, ImageStat
import cairosvg
import vtracer

ROOT=Path(__file__).resolve().parents[2]
ASSETS=ROOT/"configuracion"/"imagenes"
TARGET=ASSETS/"ilustraciones"/"transportes"
TARGET.mkdir(parents=True,exist_ok=True)
KINDS=("avion","tren","ferry","autobus","coche")
# Only the existing originals, never the prior low-quality hand-drawn SVGs.
MAX_COMPOSITED_MAE=48.0

def make_svg(original:Path,output:Path) -> tuple[float,int]:
    with Image.open(original) as im:
        img=im.convert("RGBA")
    if img.size!=(320,210):
        raise ValueError(f"Unexpected dimensions {original}: {img.size}")
    with tempfile.TemporaryDirectory() as tmp:
        temp=Path(tmp)
        png=temp/"original.png"
        candidate=temp/"candidate.svg"
        img.save(png)
        vtracer.convert_image_to_svg_py(
            str(png),str(candidate),
            colormode="color",
            hierarchical="stacked",
            mode="spline",
            filter_speckle=1,
            color_precision=8,
            layer_difference=4,
            corner_threshold=55,
            length_threshold=3.5,
            max_iterations=10,
            splice_threshold=40,
            path_precision=3
        )
        svg=candidate.read_text(encoding="utf-8")
        if "<image" in svg or "data:image/" in svg:
            raise ValueError(f"Not a true vector SVG: {original}")
        root=ET.fromstring(svg)
        shape_count=sum(el.tag.split("}")[-1] in ("path","polygon","rect","circle","ellipse") for el in root.iter())
        if shape_count<50:
            raise ValueError(f"Too few paths to represent detailed illustration: {shape_count}")
        try:
            rendered=Image.open(BytesIO(cairosvg.svg2png(bytestring=svg.encode("utf-8"),output_width=320,output_height=210))).convert("RGBA")
        except Exception as exc:
            raise ValueError(f"Unrenderable SVG: {original}") from exc

        # Comparing both dark and light composite avoids accidental loss of transparency.
        errors=[]
        for bg in ("#fffaf1","#222e30"):
            src=Image.new("RGBA",img.size,bg)
            src.alpha_composite(img)
            dst=Image.new("RGBA",img.size,bg)
            dst.alpha_composite(rendered)
            d=ImageChops.difference(src.convert("RGB"),dst.convert("RGB"))
            errors.append(sum(ImageStat.Stat(d).mean)/3.0)
        mae=max(errors)
        print(f"{original.name}: {shape_count} vector shapes, visual MAE={mae:.2f}, raw size={len(svg)} chars",flush=True)
        if mae>MAX_COMPOSITED_MAE:
            raise ValueError(f"{original.name}: failed visual-similarity gate ({mae:.2f}>{MAX_COMPOSITED_MAE})")

        # Keep SVG contents in native 320 x 210 coordinates; vector geometry
        # means the browser can scale it without pixelated edges.
        # The XML generated by VTracer is not repainted or redesigned.
        output.write_text(svg,encoding="utf-8")
        return mae,shape_count

for name in KINDS:
    make_svg(ASSETS/f"como-llegar-{name}-vcc.webp", TARGET/f"transporte-{name}.svg")

# Invalidate cached original bitmap wrappers and old HQ versions in references.
HTML=ROOT/"destinos"/"suecia"/"estocolmo"/"como-llegar.html"
CSS=ROOT/"configuracion"/"css"/"plantillas"/"como-llegar-vcc.css"
VERSION="20261106-svg-vector-real-v1"
for path in (HTML,CSS):
    content=path.read_text(encoding="utf-8")
    for name in KINDS:
        asset=f"/configuracion/imagenes/ilustraciones/transportes/transporte-{name}.svg"
        content=re.sub(re.escape(asset)+r"""(?:\?[^"'<> )]*)?""",lambda match,asset=asset:asset+"?v="+VERSION,content)
    if path==HTML:
        css_asset="/configuracion/css/plantillas/como-llegar-vcc.css"
        content=re.sub(re.escape(css_asset)+r"""(?:\?[^"'<> )]*)?""",lambda match:css_asset+"?v="+VERSION,content)
    path.write_text(content,encoding="utf-8")

print("All five SVGs contain real vector paths, render successfully, and pass the image-comparison gate.")
